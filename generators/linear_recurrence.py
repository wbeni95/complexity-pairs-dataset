    lam = growth_rate(coeffs)
    lam_s = f"{lam:.10f}"
    support = [i for i, c in enumerate(coeffs, 1) if c]
    n_lo = math.ceil(math.log(NAIVE_CALLS_LOW) / math.log(lam))
    n_hi = math.floor(math.log(NAIVE_CALLS_HIGH) / math.log(lam))
    step = max(1, (n_hi - n_lo) // 5)
    naive_ns = list(range(n_lo, n_hi + 1, step))[:7]
    v1_max = math.floor(math.log(2e5) / math.log(lam))
    poly = " + ".join(f"x^{k - i}" if k - i > 1 else ("x" if k - i == 1 else "1") for i in support)
