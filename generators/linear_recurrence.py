def write(coeffs: list[int], force: bool = False, root: Path = REPO / "synthetic") -> Path:
    target = root / entry_id(coeffs)
    if target.exists() and not force:
        raise FileExistsError(f"{target} exists (use --force to regenerate)")
    for rel, text in build(coeffs).items():
        path = target / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return target


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("coeffs", nargs="+", type=int, help="c_1 ... c_k (c_k may be zero only if some earlier c is nonzero)")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    if args.coeffs[-1] == 0:
        print("c_k must be nonzero (otherwise the recurrence has smaller order)", file=sys.stderr)
        return 2
    path = write(args.coeffs, args.force)
    print(f"wrote {path.relative_to(REPO).as_posix()}  (lambda = {growth_rate(args.coeffs):.10f})")
    return 0


