def growth_rate(coeffs: list[int]) -> float:
    """Largest real root of x^k - sum_{i in S} x^(k-i), S = {i : c_i != 0}; requires |S| >= 2."""
    k = len(coeffs)
    support = [i for i, c in enumerate(coeffs, 1) if c]
    if len(support) < 2:
        raise ValueError("need at least two nonzero coefficients, otherwise the naive recursion is not exponential")
    f = lambda x: x ** k - sum(x ** (k - i) for i in support)  # noqa: E731
    lo, hi = 1.0, 2.0  # f(1) = 1 - |S| < 0 and f(2) = 2^k - sum 2^(k-i) > 0 for any support
    for _ in range(200):
        mid = (lo + hi) / 2
        if f(mid) < 0:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


