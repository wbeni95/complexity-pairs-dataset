def naive_call_counts(coeffs: list[int], n_max: int) -> list[int]:
    """C(0..n_max): calls of the naive solve(n), outer call included (PROOFS.md section 2)."""
    k = len(coeffs)
    support = [i for i, c in enumerate(coeffs, 1) if c]
    C = []
    for n in range(n_max + 1):
        C.append(1 if n < k else 1 + sum(C[n - i] for i in support))
    return C


def matrix_mul_calls(k: int, n: int) -> int:
    """Calls of _mul made by the companion-matrix solve(n) for n >= k: bit length plus number of 1 bits of n-k+1."""
    e = n - k + 1
    return e.bit_length() + bin(e).count("1")


