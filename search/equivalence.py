"""Equivalence of square matrix multiplication schemes over GF(2): the symmetry group, invariants, and an exact
(complete) equivalence test.

Convention (search/gf2mm.py): T<n,n,n> = sum_{i,j,k} a_ij (x) b_jk (x) c_ki; a factor is an n x n 0/1 matrix stored
as an int, bit n*row + col; alpha is indexed (i, j), beta (j, k), gamma (k, i).

The group G used here (it is the group generated by the transformations listed by Kauers & Moosbauer, "Flip graphs
for matrix multiplication", ISSAC 2023, section 2, who refer to de Groote 1978 for it; AlphaTensor's
nonequivalence notebook uses the same sandwich action u -> A u B^-1, v -> B v C^-1, w -> C w A^-1):

  * sandwich  g = (P, Q, R) in GL(n,2)^3:   (a, b, c) -> (P a Q^-1, Q b R^-1, R c P^-1)   applied to every term;
  * cyclic    (a, b, c) -> (b, c, a);
  * transpose (a, b, c) -> (c^T, b^T, a^T);
  * and any permutation of the terms (a scheme is a multiset of terms).

Why these preserve T: with <a, X> = sum a_xy X_xy, a scheme is valid iff sum_r <a_r,X><b_r,Y><c_r,Z> = tr(XYZ) for
all X, Y, Z. Since <P a Q^-1, X> = <a, P^T X Q^-T>, the sandwich turns the left side into
tr(P^T X Y Z P^-T) = tr(XYZ); the cyclic map gives tr(ZXY) = tr(XYZ); the transpose gives
tr(Z^T Y^T X^T) = tr((XYZ)^T). (The unit tests also check validity after random group elements.)
Over GF(2) there are no non-trivial scalings of the factors. S3 = <cyclic, transpose> normalises the sandwich
part, so every element of G is (sandwich) o (one of the 6 elements of S3) o (term permutation).

Invariants. F(S) below is invariant under sandwiches and term permutations. For an S3-invariant we use the sorted
tuple of F(sigma S) over the six sigma in S3: if S' = g sigma0 S, then {sigma S'} = {g' sigma sigma0 S}, so the
multiset {F(sigma S')} equals {F(tau S)}. Hence DIFFERENT invariants PROVE inequivalence; equal invariants prove
nothing. All invariant values are built from exact integers and sorted tuples (hashes are only used as
deterministic names of colour classes; a collision could only hide a difference, never invent one).

Per-term sandwich invariants used (P, Q, R act as shown):
  rank a, rank b, rank c                         (a -> P a Q^-1 etc.)
  rank ab, rank bc, rank ca                      (ab -> P ab R^-1, bc -> Q bc P^-1, ca -> R ca Q^-1)
  rank abc, rank bca, rank cab; charpoly(abc)    (abc -> P abc P^-1 is a similarity; charpoly(abc) =
                                                  charpoly(bca) = charpoly(cab))
Pair invariants (ordered pair r, s) for the colour refinement:
  rank(a_r + a_s), rank(b_r + b_s), rank(c_r + c_s), rank a_r b_s, rank b_r c_s, rank c_r a_s,
  rank [a_r | a_s], rank [a_r ; a_s] (column/row space dimensions of the pair) and likewise for b and c,
  trace(a_r b_s c_r), trace(a_r b_r c_s), trace(a_s b_r c_r)  (traces of similarity-transformed products).

Exact test: `find_equivalence(S1, S2)` searches, for each sigma in S3, a sandwich g with g(sigma S1) = S2. A term
t of sigma S1 must be mapped to a term of S2 with the same colour (colours are sandwich-invariant), and
"g maps t to u" is the linear system  u_a Q = P t_a,  u_b R = Q t_b,  u_c P = R t_c  in the 3n^2 entries of
(P, Q, R). Backtracking over images, intersecting the solution spaces, and enumerating the remaining solution space
when it is small decides the question exactly (it returns a certificate (sigma, P, Q, R), checked by applying it).
"""
from __future__ import annotations

import hashlib
import itertools
from collections import Counter
from typing import Iterable, Sequence

Term = tuple  # (a, b, c) bitmasks


# --------------------------------------------------------------------------------------------- GF(2) matrices

def rows(x: int, n: int) -> list[int]:
    mask = (1 << n) - 1
    return [(x >> (n * r)) & mask for r in range(n)]


def from_rows(rs: Sequence[int], n: int) -> int:
    out = 0
    for r, v in enumerate(rs):
        out |= v << (n * r)
    return out


def mul(x: int, y: int, n: int) -> int:
    """Matrix product over GF(2) of two n x n bit matrices."""
    yr = rows(y, n)
    out = 0
    for r, row in enumerate(rows(x, n)):
        acc = 0
        t = 0
        while row:
            if row & 1:
                acc ^= yr[t]
            row >>= 1
            t += 1
        out |= acc << (n * r)
    return out


def transpose(x: int, n: int) -> int:
    out = 0
    for r in range(n):
        for c in range(n):
            if (x >> (n * r + c)) & 1:
                out |= 1 << (n * c + r)
    return out


def rank_rows(vecs: Iterable[int]) -> int:
    basis: dict[int, int] = {}
    for v in vecs:
        while v:
            hb = v.bit_length() - 1
            if hb in basis:
                v ^= basis[hb]
            else:
                basis[hb] = v
                break
    return len(basis)


def rank(x: int, n: int) -> int:
    return rank_rows(rows(x, n))


def trace(x: int, n: int) -> int:
    return sum((x >> (n * i + i)) & 1 for i in range(n)) & 1


def identity(n: int) -> int:
    return sum(1 << (n * i + i) for i in range(n))


def inverse(x: int, n: int) -> int | None:
    """Inverse over GF(2), or None if singular (Gauss-Jordan on [x | I])."""
    aug = [(r << n) | (1 << i) for i, r in enumerate(rows(x, n))]  # high n bits: x row, low n bits: identity row
    # column c of x is bit n + c of aug rows
    for col in range(n):
        piv = next((i for i in range(col, n) if (aug[i] >> (n + col)) & 1), None)
        if piv is None:
            return None
        aug[col], aug[piv] = aug[piv], aug[col]
        for i in range(n):
            if i != col and (aug[i] >> (n + col)) & 1:
                aug[i] ^= aug[col]
    mask = (1 << n) - 1
    return from_rows([a & mask for a in aug], n)


def _clmul(p: int, q: int) -> int:
    out = 0
    while q:
        if q & 1:
            out ^= p
        q >>= 1
        p <<= 1
    return out


def charpoly(x: int, n: int) -> int:
    """Characteristic polynomial det(tI + x) over GF(2) as a bitmask (bit d = coefficient of t^d).
    In characteristic 2 the determinant equals the permanent, so we sum over all permutations (n <= 4 here)."""
    ent = [[((x >> (n * r + c)) & 1) | ((1 << 1) if r == c else 0) for c in range(n)] for r in range(n)]
    total = 0
    for perm in itertools.permutations(range(n)):
        prod = 1
        for r in range(n):
            e = ent[r][perm[r]]
            if not e:
                prod = 0
                break
            prod = _clmul(prod, e)
        total ^= prod
    return total


def hstack_rank(x: int, y: int, n: int) -> int:
    """rank of the n x 2n matrix [x | y]."""
    return rank_rows((rx << n) | ry for rx, ry in zip(rows(x, n), rows(y, n)))


def vstack_rank(x: int, y: int, n: int) -> int:
    """rank of the 2n x n matrix [x ; y]."""
    return rank_rows(rows(x, n) + rows(y, n))


def random_gl(n: int, rng) -> int:
    while True:
        x = rng.getrandbits(n * n)
        if rank(x, n) == n:
            return x


# --------------------------------------------------------------------------------------------- group action

def apply_sandwich(terms: Iterable[Term], P: int, Q: int, R: int, n: int) -> list[Term]:
    Pi, Qi, Ri = inverse(P, n), inverse(Q, n), inverse(R, n)
    if Pi is None or Qi is None or Ri is None:
        raise ValueError("P, Q, R must be invertible")
    return [(mul(mul(P, a, n), Qi, n), mul(mul(Q, b, n), Ri, n), mul(mul(R, c, n), Pi, n)) for a, b, c in terms]


def cyclic(terms: Iterable[Term]) -> list[Term]:
    return [(b, c, a) for a, b, c in terms]


def transposed(terms: Iterable[Term], n: int) -> list[Term]:
    return [(transpose(c, n), transpose(b, n), transpose(a, n)) for a, b, c in terms]


S3_NAMES = ("id", "cyc", "cyc2", "tr", "tr.cyc", "tr.cyc2")


def s3_images(terms: Sequence[Term], n: int) -> dict[str, list[Term]]:
    """The six images sigma(S), sigma in S3 = <cyclic, transpose>; 'tr.cyc' means transpose after cyclic."""
    t0 = list(terms)
    c1 = cyclic(t0)
    c2 = cyclic(c1)
    return {"id": t0, "cyc": c1, "cyc2": c2, "tr": transposed(t0, n), "tr.cyc": transposed(c1, n),
            "tr.cyc2": transposed(c2, n)}


def canonical_terms(terms: Iterable[Term]) -> tuple:
    return tuple(sorted(tuple(t) for t in terms))


# --------------------------------------------------------------------------------------------- invariants

def factor_rank_profile(terms: Iterable[Term], n: int) -> tuple:
    """RL-059's invariant: multiset of sorted factor-rank triples (S3- and sandwich-invariant)."""
    c = Counter(tuple(sorted((rank(a, n), rank(b, n), rank(c_, n)))) for a, b, c_ in terms)
    return tuple(sorted(c.items()))


def ordered_rank_profile(terms: Iterable[Term], n: int) -> tuple:
    """Sandwich-invariant: multiset of ORDERED factor-rank triples (not S3-invariant on its own)."""
    c = Counter((rank(a, n), rank(b, n), rank(c_, n)) for a, b, c_ in terms)
    return tuple(sorted(c.items()))


def term_label(t: Term, n: int) -> tuple:
    """Sandwich-invariant label of a single term (see module docstring)."""
    a, b, c = t
    ab, bc, ca = mul(a, b, n), mul(b, c, n), mul(c, a, n)
    abc, bca, cab = mul(ab, c, n), mul(bc, a, n), mul(ca, b, n)
    return (rank(a, n), rank(b, n), rank(c, n), rank(ab, n), rank(bc, n), rank(ca, n),
            rank(abc, n), rank(bca, n), rank(cab, n), charpoly(abc, n))


def term_profile(terms: Iterable[Term], n: int) -> tuple:
    """Sandwich-invariant: multiset of term labels."""
    return tuple(sorted(Counter(term_label(t, n) for t in terms).items()))


def pair_label(t: Term, u: Term, n: int) -> tuple:
    """Sandwich-invariant label of an ordered pair of terms (see module docstring)."""
    a1, b1, c1 = t
    a2, b2, c2 = u
    return (rank(a1 ^ a2, n), rank(b1 ^ b2, n), rank(c1 ^ c2, n),
            rank(mul(a1, b2, n), n), rank(mul(b1, c2, n), n), rank(mul(c1, a2, n), n),
            hstack_rank(a1, a2, n), vstack_rank(a1, a2, n), hstack_rank(b1, b2, n), vstack_rank(b1, b2, n),
            hstack_rank(c1, c2, n), vstack_rank(c1, c2, n),
            trace(mul(mul(a1, b2, n), c1, n), n), trace(mul(mul(a1, b1, n), c2, n), n),
            trace(mul(mul(a2, b1, n), c1, n), n))


def _h(obj) -> str:
    return hashlib.sha256(repr(obj).encode()).hexdigest()[:24]


def wl_colours(terms: Sequence[Term], n: int, rounds: int = 3) -> tuple[list[str], tuple]:
    """1-dimensional colour refinement (Weisfeiler-Leman) on the complete graph of terms, with term labels as
    vertex colours and ordered pair labels as edge colours. Returns (colour of each term, invariant), where the
    invariant is the tuple of colour histograms after every round. Both are sandwich-invariant and do not depend
    on the order of the terms (colours are content hashes of sorted multisets)."""
    t = list(terms)
    r = len(t)
    col = [_h(("v", term_label(x, n))) for x in t]
    edge = [[None] * r for _ in range(r)]
    for i in range(r):
        for j in range(r):
            if i != j:
                edge[i][j] = _h(("e", pair_label(t[i], t[j], n)))
    hist = [tuple(sorted(Counter(col).items()))]
    for _ in range(rounds):
        new = []
        for i in range(r):
            sig = sorted((edge[i][j], edge[j][i], col[j]) for j in range(r) if j != i)
            new.append(_h((col[i], tuple(sig))))
        col = new
        hist.append(tuple(sorted(Counter(col).items())))
    return col, tuple(hist)


def s3_invariant(terms: Sequence[Term], n: int, F) -> tuple:
    """Sorted tuple of F(sigma S) over the six sigma in S3 (F must be sandwich- and permutation-invariant)."""
    return tuple(sorted(F(img, n) for img in s3_images(terms, n).values()))


def invariants(terms: Sequence[Term], n: int, wl: bool = False) -> dict:
    """All S3 x sandwich invariants, from coarse to fine."""
    out = {"factor_rank_profile": factor_rank_profile(terms, n),
           "ordered_rank_profile_S3": s3_invariant(terms, n, ordered_rank_profile),
           "term_profile_S3": s3_invariant(terms, n, term_profile)}
    if wl:
        out["wl_S3"] = s3_invariant(terms, n, lambda s, nn: wl_colours(s, nn)[1])
    return out


def first_difference(inv1: dict, inv2: dict) -> str | None:
    """Name of the coarsest invariant on which the two invariant dicts differ, or None."""
    for k in ("factor_rank_profile", "ordered_rank_profile_S3", "term_profile_S3", "wl_S3"):
        if k in inv1 and k in inv2 and inv1[k] != inv2[k]:
            return k
    return None


# --------------------------------------------------------------------------------------------- exact test

class _LinSys:
    """Homogeneous linear system over GF(2) in N unknowns, kept in reduced row echelon form."""

    def __init__(self, N: int, piv: dict | None = None):
        self.N = N
        self.piv = dict(piv or {})  # pivot bit -> row

    def copy(self):
        return _LinSys(self.N, self.piv)

    def add(self, row: int) -> None:
        for p, v in self.piv.items():
            if (row >> p) & 1:
                row ^= v
        if not row:
            return
        p = row.bit_length() - 1
        for q in list(self.piv):
            if (self.piv[q] >> p) & 1:
                self.piv[q] ^= row
        self.piv[p] = row

    def nullity(self) -> int:
        return self.N - len(self.piv)

    def null_basis(self) -> list[int]:
        free = [b for b in range(self.N) if b not in self.piv]
        basis = []
        for f in free:
            x = 1 << f
            for p, v in self.piv.items():
                if (v >> f) & 1:
                    x |= 1 << p
            basis.append(x)
        return basis


def _map_equations(t: Term, u: Term, n: int) -> list[int]:
    """Rows of the linear system 'sandwich maps term t to term u':  u_a Q + P t_a = 0, u_b R + Q t_b = 0,
    u_c P + R t_c = 0. Unknown bits: P entry (r,c) -> n*r+c, Q -> n^2 + n*r+c, R -> 2n^2 + n*r+c."""
    nn = n * n
    offs = {"P": 0, "Q": nn, "R": 2 * nn}
    eqs = []
    for (left, X, right, Y) in ((u[0], "Q", t[0], "P"), (u[1], "R", t[1], "Q"), (u[2], "P", t[2], "R")):
        # (left * X)_{rc} + (Y * right)_{rc} = 0
        for r in range(n):
            for c in range(n):
                row = 0
                for s in range(n):
                    if (left >> (n * r + s)) & 1:
                        row ^= 1 << (offs[X] + n * s + c)
                    if (right >> (n * s + c)) & 1:
                        row ^= 1 << (offs[Y] + n * r + s)
                eqs.append(row)
    return eqs


def _split(x: int, n: int) -> tuple[int, int, int]:
    nn = n * n
    m = (1 << nn) - 1
    return x & m, (x >> nn) & m, (x >> (2 * nn)) & m


def find_sandwich(S1: Sequence[Term], S2: Sequence[Term], n: int, enum_limit: int = 14):
    """Exact search for (P, Q, R) with sandwich(S1) = S2 as multisets. Returns (P, Q, R) or None.
    Complete: every candidate image of every base term that is compatible with the sandwich-invariant colours is
    tried, and a solution space is enumerated in full before it is discarded."""
    if len(S1) != len(S2):
        return None
    col1, inv1 = wl_colours(S1, n)
    col2, inv2 = wl_colours(S2, n)
    if inv1 != inv2:
        return None
    target = Counter(canonical_terms(S2))
    cls2: dict[str, list[int]] = {}
    for j, cc in enumerate(col2):
        cls2.setdefault(cc, []).append(j)
    # base terms: rarest colour classes first
    order = sorted(range(len(S1)), key=lambda i: (len(cls2[col1[i]]), col1[i], i))
    N = 3 * n * n

    def check(x):
        P, Q, R = _split(x, n)
        if rank(P, n) < n or rank(Q, n) < n or rank(R, n) < n:
            return None
        img = apply_sandwich(S1, P, Q, R, n)
        if Counter(canonical_terms(img)) == target:
            return P, Q, R
        return None

    def rec(depth, sys_, used):
        k = sys_.nullity()
        if k == 0:
            return None
        if k <= enum_limit or depth == len(order):
            basis = sys_.null_basis()
            for mask in range(1, 1 << len(basis)):
                x = 0
                for i, b in enumerate(basis):
                    if (mask >> i) & 1:
                        x ^= b
                res = check(x)
                if res:
                    return res
            return None
        i = order[depth]
        for j in cls2[col1[i]]:
            if j in used:
                continue
            s2 = sys_.copy()
            for e in _map_equations(S1[i], S2[j], n):
                s2.add(e)
            res = rec(depth + 1, s2, used | {j})
            if res:
                return res
        return None

    return rec(0, _LinSys(N), frozenset())


def find_equivalence(S1: Sequence[Term], S2: Sequence[Term], n: int):
    """Exact equivalence test under G. Returns (sigma_name, P, Q, R) with sandwich_{P,Q,R}(sigma(S1)) = S2,
    verified by applying it, or None if no element of G maps S1 to S2."""
    for name, img in s3_images(S1, n).items():
        res = find_sandwich(img, S2, n)
        if res:
            P, Q, R = res
            assert Counter(canonical_terms(apply_sandwich(img, P, Q, R, n))) == Counter(canonical_terms(S2))
            return (name, P, Q, R)
    return None
