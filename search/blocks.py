"""Start schemes for flip-graph walks built from smaller verified schemes (research/2026-10-06d_exotic_formats.md).

Convention as in search/gf2mm.py: T<n,m,p> = sum a_ij (x) b_jk (x) c_ki; alpha bit i*m+j, beta bit j*p+k,
gamma bit k*n+i.

* `cyclic(fmt, terms)`: (n,m,p) -> (m,p,n), (a,b,c) -> (b,c,a). The bit layouts already match, since gamma of the
  new format (m,p,n) is indexed (i, j) with bit i*m + j, which is alpha's layout.
* `transpose(fmt, terms)`: (n,m,p) -> (p,m,n), from (AB)^T = B^T A^T: (a,b,c) -> (b^T, a^T, c^T).
* `to_format(fmt, terms, target)`: one of the six images under <cyclic, transpose> whose format is `target`.
* `embed(fmt, terms, big, offset)`: the scheme as a block of the format `big`, at block offset (di, dj, dk):
  rows i+di of A and C, rows j+dj of B / columns j+dj of A, columns k+dk of B / rows k+dk of C.
* `direct_sum(axis, (fmt1, terms1), (fmt2, terms2))`: block split of one dimension (axis 0 = n, 1 = m, 2 = p).
  Splitting n or p gives two independent products; splitting m gives C = A1 B1 + A2 B2. In all three cases the
  index cube {(i, j, k)} is partitioned, so the sum of the two embedded tensors is T<big>.

Every function returns plain terms; callers verify with gf2mm.verify (the tests do, and so does `best_block_start`).
"""
from __future__ import annotations

import itertools
from pathlib import Path

from . import gf2mm


def _transpose_bits(x: int, rows: int, cols: int) -> int:
    out = 0
    for r in range(rows):
        for c in range(cols):
            if (x >> (r * cols + c)) & 1:
                out |= 1 << (c * rows + r)
    return out


def cyclic(fmt, terms):
    n, m, p = fmt
    return (m, p, n), [(b, c, a) for a, b, c in terms]


def transpose(fmt, terms):
    n, m, p = fmt
    return (p, m, n), [(_transpose_bits(b, m, p), _transpose_bits(a, n, m), _transpose_bits(c, p, n))
                       for a, b, c in terms]


def images(fmt, terms):
    """The six images under the group generated by `cyclic` and `transpose`: list of (format, terms)."""
    out = []
    f, t = tuple(fmt), list(terms)
    for _ in range(3):
        out.append((f, t))
        out.append(transpose(f, t))
        f, t = cyclic(f, t)
    return out


def to_format(fmt, terms, target):
    target = tuple(target)
    for f, t in images(fmt, terms):
        if f == target:
            return t
    raise ValueError(f"{tuple(fmt)} is not a permutation of {target}")


def embed(fmt, terms, big, offset):
    n, m, p = fmt
    N, M, P = big
    di, dj, dk = offset
    if di + n > N or dj + m > M or dk + p > P:
        raise ValueError("block does not fit")

    def move(x, rows, cols, dr, dc, cols_big):
        out = 0
        for r in range(rows):
            for c in range(cols):
                if (x >> (r * cols + c)) & 1:
                    out |= 1 << ((r + dr) * cols_big + (c + dc))
        return out

    return [(move(a, n, m, di, dj, M), move(b, m, p, dj, dk, P), move(c, p, n, dk, di, N)) for a, b, c in terms]


def direct_sum(axis, part1, part2):
    (f1, t1), (f2, t2) = part1, part2
    f1, f2 = tuple(f1), tuple(f2)
    for ax in range(3):
        if ax != axis and f1[ax] != f2[ax]:
            raise ValueError("the other two dimensions must agree")
    big = list(f1)
    big[axis] = f1[axis] + f2[axis]
    big = tuple(big)
    off = [0, 0, 0]
    off[axis] = f1[axis]
    return big, embed(f1, t1, big, (0, 0, 0)) + embed(f2, t2, big, tuple(off))


def trivial_scheme(fmt):
    """The standard algorithm, which is optimal when one dimension is 1 (rank = product of the other two)."""
    return gf2mm.standard_scheme(fmt)


def load_library(paths):
    """Verified schemes from JSON files (gf2mm format): {sorted format: (rank, fmt, terms, path)}, best per format.
    A file is used only if it passes both exact verifiers."""
    lib = {}
    for path in paths:
        fmt, terms, _ = gf2mm.load_scheme(path)
        key = tuple(sorted(fmt))
        if key in lib and lib[key][0] <= len(terms):
            continue
        if gf2mm.verify(fmt, terms) and gf2mm.verify_explicit(fmt, terms):
            lib[key] = (len(terms), tuple(fmt), terms, str(path))
    return lib


def best_rank(lib, fmt):
    """Rank available for `fmt` from the library, the standard algorithm, or a strassen-type 2x2x2 scheme."""
    key = tuple(sorted(fmt))
    cands = [fmt[0] * fmt[1] * fmt[2]]
    if key in lib:
        cands.append(lib[key][0])
    return min(cands)


def scheme_for(lib, fmt):
    key = tuple(sorted(fmt))
    if key in lib and lib[key][0] < fmt[0] * fmt[1] * fmt[2]:
        _, f, t, _ = lib[key]
        return to_format(f, t, fmt)
    return trivial_scheme(fmt)


def best_block_start(lib, fmt):
    """Best single split of one dimension of `fmt` into two blocks, each realised by the library (or the standard
    algorithm). Returns (rank, description, terms), verified with gf2mm.verify."""
    fmt = tuple(fmt)
    best = (fmt[0] * fmt[1] * fmt[2], "standard algorithm", gf2mm.standard_scheme(fmt))
    for axis in range(3):
        for s in range(1, fmt[axis] // 2 + 1):
            f1 = list(fmt)
            f2 = list(fmt)
            f1[axis], f2[axis] = s, fmt[axis] - s
            f1, f2 = tuple(f1), tuple(f2)
            r = best_rank(lib, f1) + best_rank(lib, f2)
            if r < best[0]:
                big, terms = direct_sum(axis, (f1, scheme_for(lib, f1)), (f2, scheme_for(lib, f2)))
                assert big == fmt
                if not gf2mm.verify(fmt, terms):
                    raise AssertionError(f"block start for {fmt} failed verification")
                best = (len(terms), f"{f1} + {f2} (split of dimension {axis})", terms)
    return best


def default_library_paths(root: Path):
    """Verified schemes saved by earlier rounds (our own rediscoveries) plus Strassen's scheme handled separately."""
    dirs = [root / "search" / "schemes" / d for d in ("rust-2026-10-07b", "rust-2026-10-06c", "rust-2026-10-07")]
    return sorted(p for d in dirs if d.exists() for p in d.glob("*.json"))


def strassen_entry():
    return {(2, 2, 2): (7, (2, 2, 2), gf2mm.strassen_scheme(), "gf2mm.strassen_scheme")}


def all_permutations(fmt):
    return sorted(set(itertools.permutations(fmt)))
