#!/usr/bin/env python3
"""Dataset statistics: counts by tag, level, model, location, domain and technique (pattern mining, 2026-10-07).

Question: what does the dataset contain right now, and where are the gaps? This script answers it from the
entry.json files on disk (not from index.json, which is regenerated by tools/build_index.py and can lag behind)
and from the proposed technique mapping research/2026-10-07_technique_mapping.json.

Counting rules:
  * an "entry" is a folder under pairs/, staging/ or synthetic/ that contains entry.json; folders without one
    (work in progress) are listed separately;
  * "validated pair" follows RESEARCH_LOG RL-010: level V1+ in pairs/ with any of T1-T5, T8, T9 as primary or
    secondary tag;
  * models are counted per algorithm (an entry with three algorithms contributes three);
  * techniques are counted per entry from the mapping's pair-level "transformation" list, and separately per
    algorithm from the algorithm-level "techniques" lists; baselines are counted per slow algorithm.
Entries on disk that the mapping does not cover are reported as UNMAPPED (they were added after the mapping was
written); mapping records with no entry on disk are reported as STALE.

Deterministic: no randomness, no timing, sorted output. The numbers change only when entries are added, edited
or removed (other agents added entries during the 2026-10-07 session, so a rerun later may differ).

Result: the output of the run used in research/2026-10-07_patterns.md is reproduced in that file's appendix.

Usage (repository root):  PYTHONIOENCODING=utf-8 ./.venv/Scripts/python experiments/2026-10-07_dataset_stats.py
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LOCATIONS = ("pairs", "staging", "synthetic")
MAPPING = REPO / "research" / "2026-10-07_technique_mapping.json"
COUNTED_TAGS = {"T1", "T2", "T3", "T4", "T5", "T8", "T9"}
LEVEL_ORDER = ["V0", "V1", "V2", "V3"]
TAG_ORDER = [f"T{i}" for i in range(1, 10)]


def load_entries():
    entries, wip = [], []
    for loc in LOCATIONS:
        base = REPO / loc
        for d in sorted(p for p in base.iterdir() if p.is_dir() and not p.name.startswith(("_", "."))):
            f = d / "entry.json"
            if f.is_file():
                entries.append((loc, json.loads(f.read_text(encoding="utf-8"))))
            elif d.name != "__pycache__":
                wip.append(f"{loc}/{d.name}")
    return entries, wip


def table(title, counter, order=None, total=None):
    print(f"\n{title}")
    keys = order if order else sorted(counter, key=lambda k: (-counter[k], k))
    for k in keys:
        if counter.get(k, 0) or order:
            print(f"  {k:<40} {counter.get(k, 0):>4}")
    if total is not None:
        print(f"  {'(total)':<40} {total:>4}")


def main() -> int:
    entries, wip = load_entries()
    print(f"entries with entry.json: {len(entries)}")
    if wip:
        print("folders without entry.json (work in progress, not counted): " + ", ".join(wip))

    loc_c = Counter(loc for loc, _ in entries)
    table("by location", loc_c, list(LOCATIONS), len(entries))

    prim = Counter(e["pair_type"] for _, e in entries)
    table("by primary tag (all locations)", prim, TAG_ORDER)
    anytag = Counter(t for _, e in entries for t in {e["pair_type"], *e.get("secondary_tags", [])})
    table("by tag, primary or secondary (all locations)", anytag, TAG_ORDER)

    lvl = Counter(e["verification"]["level"] for _, e in entries)
    table("by verification level", lvl, LEVEL_ORDER)
    print("\nlocation x level")
    for loc in LOCATIONS:
        c = Counter(e["verification"]["level"] for l, e in entries if l == loc)
        print(f"  {loc:<10} " + "  ".join(f"{lv}={c.get(lv, 0)}" for lv in LEVEL_ORDER))

    validated = [e["id"] for loc, e in entries
                 if loc == "pairs" and e["verification"]["level"] != "V0"
                 and {e["pair_type"], *e.get("secondary_tags", [])} & COUNTED_TAGS]
    print(f"\nvalidated pairs (RL-010 rule): {len(validated)}")
    print(f"T7 synthetic entries (never counted): {sum(1 for _, e in entries if e['pair_type'] == 'T7')}")

    models = Counter(a["model"] for _, e in entries for a in e["algorithms"])
    table("algorithms by model (per algorithm)", models, None, sum(models.values()))
    impl = Counter(("implemented" if a.get("implementation") else "not implemented") for _, e in entries for a in e["algorithms"])
    table("algorithms implemented", impl)
    q_entries = sorted(e["id"] for _, e in entries if any(a["model"] == "quantum" for a in e["algorithms"]))
    r_entries = sorted(e["id"] for _, e in entries if any(a["model"] == "classical-randomized" for a in e["algorithms"]))
    print(f"\nentries with a quantum algorithm: {len(q_entries)}: {', '.join(q_entries)}")
    print(f"entries with a classical-randomized algorithm: {len(r_entries)}: {', '.join(r_entries)}")
    lb = sorted(e["id"] for _, e in entries if e.get("lower_bounds"))
    print(f"entries with lower_bounds: {len(lb)}: {', '.join(lb)}")
    print(f"entries with verification.proofs (V3 material): {sum(1 for _, e in entries if e['verification'].get('proofs'))}")

    # ------------------------------------------------------------ mapping-based statistics
    if not MAPPING.is_file():
        print(f"\n(no mapping file at {MAPPING.relative_to(REPO)}; technique statistics skipped)")
        return 0
    mp = json.loads(MAPPING.read_text(encoding="utf-8"))
    by_id = {m["id"]: m for m in mp["mapping"]}
    on_disk = {e["id"]: (loc, e) for loc, e in entries}
    unmapped = sorted(set(on_disk) - set(by_id))
    stale = sorted(set(by_id) - set(on_disk))
    print(f"\nmapping: {len(by_id)} records; UNMAPPED entries on disk: {unmapped or 'none'}; STALE records: {stale or 'none'}")
    mapped = [(on_disk[i][0], on_disk[i][1], by_id[i]) for i in sorted(set(on_disk) & set(by_id))]
    name_mismatch = [i for _, e, m in mapped if [a["name"] for a in e["algorithms"]] != [a["name"] for a in m["algorithms"]]]
    print(f"mapping records whose algorithm names no longer match the entry: {name_mismatch or 'none'}")

    tech_names = {t["id"]: t["name"] for t in mp["techniques"]}
    for scope, sel in (("all mapped entries", lambda loc: True),
                       ("pairs/ only", lambda loc: loc == "pairs"),
                       ("staging/ only", lambda loc: loc == "staging"),
                       ("synthetic/ only", lambda loc: loc == "synthetic")):
        c = Counter(t for loc, _, m in mapped if sel(loc) for t in m["transformation"])
        table(f"pair-level transformation technique ({scope}; an entry can have several)", c)
    alg_c = Counter(t for loc, _, m in mapped if loc != "synthetic" for a in m["algorithms"] for t in a["techniques"])
    table("algorithm-level technique use (pairs/ + staging/, per algorithm)", alg_c)
    unused = sorted(set(tech_names) - set(alg_c) - {t for _, _, m in mapped for t in m["transformation"]})
    print(f"\nvocabulary techniques used by NO mapped entry (candidate-only so far): {', '.join(unused)}")
    base_c = Counter(a["baseline"] for loc, _, m in mapped if loc != "synthetic" for a in m["algorithms"] if a["baseline"])
    table("baseline kind of slow algorithms (pairs/ + staging/)", base_c)
    dom = Counter(m["domain"] for loc, _, m in mapped if loc != "synthetic")
    table("domain (pairs/ + staging/)", dom)
    dom_p = Counter(m["domain"] for loc, _, m in mapped if loc == "pairs")
    table("domain (pairs/ only)", dom_p)

    print("\nprimary tag x transformation technique (pairs/ + staging/)")
    cross = defaultdict(Counter)
    for loc, e, m in mapped:
        if loc == "synthetic":
            continue
        for t in m["transformation"]:
            cross[e["pair_type"]][t] += 1
    for tag in TAG_ORDER:
        if cross[tag]:
            print(f"  {tag}: " + ", ".join(f"{t}={n}" for t, n in sorted(cross[tag].items(), key=lambda kv: (-kv[1], kv[0]))))
    prov = sorted(m["id"] for m in mp["mapping"] if m.get("provisional"))
    print(f"\nprovisional mapping records (entries added during the session): {', '.join(prov) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
